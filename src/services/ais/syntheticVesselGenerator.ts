export function generateInitialSyntheticFleet(): AISVesselTarget[] {
  const now = Date.now();
  return GLOBAL_SHIPPING_LANE_SEEDS.map((seed, idx) => ({
    targetId: `AIS_${seed.mmsi}`,
    mmsi: seed.mmsi,
    imo: seed.imo,
    vesselName: seed.name,
    vesselType: seed.type,
    position: {
      latitude: makeLat(seed.lat),
      longitude: makeLon(seed.lon),
    },
    sogKn: makeKn(seed.sogKn),
    cogDeg: seed.cogDeg,
    headingDeg: seed.cogDeg,
    draftM: seed.draftM,
    destinationPort: seed.dest,
    eta: makeUnixMs(now + 86400000 * (2 + (idx % 12))),
    navigationStatus: seed.type === "Sailboat" ? "UNDERWAY_SAIL" : "UNDERWAY_ENGINE",
    source: "SYNTHETIC_OCEAN",
    observedAt: makeUnixMs(now),
    receivedAt: makeUnixMs(now),
    isCollectedInShipBook: false,
    positionUncertaintyM: 8,
  }));
}
